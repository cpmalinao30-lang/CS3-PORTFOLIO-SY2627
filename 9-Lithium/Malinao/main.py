# math_utils.py

def add_numbers(a, b):

    return a + b

def multiply_numbers(a, b):

    return a * b

def greet_user(name):

    return f"Hello, {name}! Welcome to VS Code."

def main():
    print(add_numbers(15, 10))

    print(multiply_numbers(5, 4))

    print(greet_user("Clive"))

if __name__ == "__main__":

    main()